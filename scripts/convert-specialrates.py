#!/usr/bin/env python3
"""
Convert OPM's 2026 special salary rate file into the law enforcement special rates the engine uses.

Input:  data/raw/opm/<year>/SpecialRates_<year>.txt  (OPM bulk file, received by hand; OPM blocks scripts)
          fixed format per line: table(4) plan(2) grade(2) step(2) annual(6) effective(M/DD/YYYY)
          e.g. 0001GS05010541801/01/2026 = table 0001, GS-5 step 1, $54,180, effective 1/01/2026
        data/payorder/<year>.json  (locality %, EX-IV cap) and data/opm/<year>/leo.json (LEO base table)
        CPM 2025-25 and CPM 2026-01 (in data/raw/opm/<year>/): who is covered, and the table layout
Output: shared/data/leospecial.js  GOVPAY_DATA.leoSpecial = {year: {effective, tables: {area: [15 grades x 10 steps]}}}

CPM 2026-01: tables L001-L118 cover all grades and steps in each locality area (and outside the U.S.);
L001-L058 are on the LEO special base (pay plan GL: law enforcement officers), L060-L117 on the GS base.
The file doesn't name each table's area, so tables are matched to areas by their numbers: each must equal
the LEO base rate x (1 + locality %) x 1.038 / 1.01 (the 3.8% total raise over 2025 vs the 1% base raise)
within rounding, one table per area. Three area pairs have locality rates within 0.02% of each other
(Birmingham/Omaha, Buffalo/Milwaukee, Cleveland/Raleigh); their tables are told apart by the same test,
and the result also follows OPM's alphabetical table order. The values used are OPM's, never the formula.

Usage: python3 scripts/convert-specialrates.py 2026
"""
import json, re, sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    year = int(sys.argv[1]) if len(sys.argv) > 1 else 2026
    tables, eff = defaultdict(dict), {}
    for n, line in enumerate((ROOT / f"data/raw/opm/{year}/SpecialRates_{year}.txt").read_text(encoding="latin-1").splitlines(), 1):
        if not line.strip():
            continue
        m = re.fullmatch(r"([0-9A-Z]{4})([A-Z]{2})(\d{2})(\d{2})(\d{6})(\d{1,2}/\d{2}/\d{4})", line.strip())
        if not m:
            raise SystemExit(f"line {n} doesn't fit the format: {line!r}")
        t, plan, g, s, rate, d = m.groups()
        assert plan == "GS", (n, plan)
        assert (int(g), int(s)) not in tables[t], f"duplicate {t} GS-{g}/{s}"
        tables[t][(int(g), int(s))] = int(rate)
        assert eff.setdefault(t, d) == d, f"table {t} has more than one effective date"

    order = json.loads((ROOT / f"data/payorder/{year}.json").read_text())
    pct = {a["name"]: a["pct"] for a in order["locality"]}
    cap = order["executiveSchedule"]["IV"]
    gl = {int(k): v for k, v in json.loads((ROOT / f"data/opm/{year}/leo.json").read_text())["base"].items()}
    for t, r in tables.items():                                  # every table: steps rise, nothing over the cap
        for g in {g for g, s in r}:
            steps = [r[(g, s)] for s in range(1, 11) if (g, s) in r]
            assert steps == sorted(steps), f"{t} GS-{g} steps don't rise"
        assert max(r.values()) <= cap, f"{t} exceeds EX-IV"

    def err(t, area):
        return max(abs(v - min(round(gl[g][s - 1] * (1 + pct[area] / 100) * 1.038 / 1.01), cap)) for (g, s), v in tables[t].items())
    match = {}
    for i in range(1, 59):
        t = f"L{i:03d}"
        assert len(tables[t]) == 150, f"{t} should cover GS-1 to GS-15, all steps"
        ranked = sorted((err(t, a), a) for a in pct)
        assert ranked[0][0] <= 15, f"{t}: no area fits (best {ranked[0]})"
        assert ranked[1][0] - ranked[0][0] >= 4, f"{t}: {ranked[0][1]} and {ranked[1][1]} can't be told apart"
        match[ranked[0][1]] = t
    assert len(match) == 58 and set(match) == set(pct), "every locality area must get exactly one table"

    out = {"effective": "2026-01-11", "source": "OPM special rate tables L001-L058 (CPM 2025-25, CPM 2026-01)",
           "tables": {a: {"table": t, "rates": [[tables[t][(g, s)] for s in range(1, 11)] for g in range(1, 16)]} for a, t in sorted(match.items())}}
    doc = {"years": {str(year): out}}
    (ROOT / "shared/data/leospecial.js").write_text(
        "/* Generated by scripts/convert-specialrates.py from OPM's special rate file. Do not edit by hand. */\n"
        "(function (g) { (g.GOVPAY_DATA = g.GOVPAY_DATA || {}).leoSpecial = " + json.dumps(doc, separators=(",", ":")) +
        "; })(typeof window !== \"undefined\" ? window : globalThis);\n")
    print(f"{year}: {len(tables)} special rate tables ({sum(len(r) for r in tables.values()):,} rates) read and checked; "
          f"law enforcement tables L001-L058 matched to all 58 locality areas")
    print("  e.g.", ", ".join(f"{a.split(',')[0].split('-')[0]} {t}" for a, t in list(sorted(match.items()))[:5]))


if __name__ == "__main__":
    main()
