#!/usr/bin/env python3
"""
Build the city list: every U.S. place (city, town, or census-designated place such as
Arlington, VA or Bethesda, MD) with at least MIN_POP people, and the county it sits in.
A city inherits its county's GS locality, per diem and housing areas in the app.

Sources (official, downloaded by this script):
  Places by county   Census 2020 national_place_by_county2020.txt (every place and the counties it touches)
  Population         ACS 2020-2024 5-year table B01003 (total population, every place incl. CDPs)
  Main county        Census Vintage 2024 city/town estimates (population of each place part by county),
                     used to pick the county where most residents live when a place spans several

Output: data/places/cities.json and shared/data/cities.js (GOVPAY_DATA.cities)
Usage:  python3 scripts/build-cities.py [cache-dir]
"""
import csv, io, json, re, sys, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MIN_POP = 5000
URLS = {
    "pbc": "https://www2.census.gov/geo/docs/reference/codes2020/national_place_by_county2020.txt",
    "pop": "https://www2.census.gov/programs-surveys/acs/summary_file/2024/table-based-SF/data/5YRData/acsdt5y2024-b01003.dat",
    "sub": "https://www2.census.gov/programs-surveys/popest/datasets/2020-2024/cities/totals/sub-est2024.csv",
}
SKIP_STATES = {"PR", "AS", "GU", "MP", "UM", "VI"}           # territories are OCONUS (later)
SUFFIX = re.compile(r"\s+(city and borough|consolidated government|metropolitan government|unified government|"
                    r"metro government|urban county|city|town|village|borough|CDP|municipality|plantation|township|comunidad|zona urbana)"
                    r"(\s+\(balance\))?$", re.I)


def fetch(key, cache):
    path = cache / Path(URLS[key]).name
    if not path.exists():
        print("downloading", URLS[key])
        urllib.request.urlretrieve(URLS[key], path)
    return path


def clean(name):
    name = re.sub(r"\s+\(balance\)$", "", name)
    prev = None
    while prev != name:
        prev, name = name, SUFFIX.sub("", name).strip()
    return name


def main():
    cache = Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/census")
    cache.mkdir(parents=True, exist_ok=True)

    pop = {}
    for line in fetch("pop", cache).read_text().splitlines():
        if line.startswith("1600000US"):
            geo, est, _ = line.split("|")
            pop[geo[9:]] = int(est)

    # population of each incorporated place's part in each county
    part = {}
    with open(fetch("sub", cache), encoding="latin-1") as f:
        for r in csv.DictReader(f):
            if r["SUMLEV"] == "157":
                part.setdefault(r["STATE"] + r["PLACE"], {})[r["STATE"] + r["COUNTY"]] = int(r["POPESTIMATE2024"])

    places = {}
    for r in csv.DictReader(io.StringIO(fetch("pbc", cache).read_text(encoding="latin-1")), delimiter="|"):
        if r["STATE"] in SKIP_STATES:
            continue
        pid = r["STATEFP"] + r["PLACEFP"]
        p = places.setdefault(pid, {"name": r["PLACENAME"], "st": r["STATE"], "counties": []})
        p["counties"].append(r["STATEFP"] + r["COUNTYFP"])

    counties = json.loads((ROOT / "data/places/counties.json").read_text())
    rows_c = counties["counties"]
    cidx = {c[0]: i for i, c in enumerate(rows_c)}
    out, split, missing = [], [], 0
    for pid, p in places.items():
        n = pop.get(pid)
        if n is None:
            missing += 1
            continue
        if n < MIN_POP:
            continue
        cs = [c for c in p["counties"] if c in cidx]
        if not cs:
            continue
        if len(cs) > 1 and pid in part:
            cs.sort(key=lambda c: -part[pid].get(c, 0))
        main_c = cs[0]
        areas = {(rows_c[cidx[c]][3], rows_c[cidx[c]][4]) for c in cs}
        row = [pid[2:], clean(p["name"]), cidx[main_c], round(n / 100)]
        if len(areas) > 1:
            split.append(f"{clean(p['name'])}, {p['st']}")
            row.append(1)
        out.append(row)
    out.sort(key=lambda r: (rows_c[r[2]][2], r[1]))

    names = {(rows_c[r[2]][2], r[1].lower()) for r in out}
    for st, nm in [("TX", "houston"), ("VA", "arlington"), ("MD", "bethesda"), ("MD", "silver spring"), ("CA", "los angeles"), ("NY", "new york")]:
        assert (st, nm) in names, (st, nm)

    doc = {
        "source": "Census 2020 place-by-county list · ACS 2020-2024 5-year population (B01003) · Census Vintage 2024 place estimates",
        "minPop": MIN_POP,
        "note": "Rows are [place FIPS (5), name, index into places.counties (main county), population in hundreds, 1 if its counties fall in different locality or per diem areas].",
        "cities": out,
    }
    (ROOT / "data/places/cities.json").write_text(json.dumps(doc, separators=(",", ":")) + "\n")
    js = ("/* Generated by scripts/build-cities.py from Census files. Do not edit by hand. */\n"
          "(function (g) { (g.GOVPAY_DATA = g.GOVPAY_DATA || {}).cities = " + json.dumps(doc, separators=(",", ":")) +
          "; })(typeof window !== \"undefined\" ? window : globalThis);\n")
    (ROOT / "shared/data/cities.js").write_text(js)
    print(f"{len(out)} places with {MIN_POP:,}+ people ({missing} without an ACS estimate skipped)")
    print(f"{len(split)} span counties in different locality or per diem areas (main county used): {', '.join(split[:12])}{' ...' if len(split) > 12 else ''}")


if __name__ == "__main__":
    main()
