#!/usr/bin/env python3
"""
Build the military installation list people can search for ("Eglin", "NAS Pensacola", "Fort Hood").

Source: data/places/bases.json, hand-kept: [official name, state, ZIP on the base, extra names...].
An extra name "county:FIPS" sets the county where the ZIP's own county is wrong for the base.
Each base takes from its ZIP (data/bah/zips-*.json, DTMO + Census) the DTMO housing area for BAH and
the main county, which gives the GS locality area, per diem area and wage area in the app. An on-base
ZIP with no Census ZIP area borrows the most common county among ZIPs with the same first three digits
and housing area (the same rule site/scripts/copy-assets.mjs uses for ZIP lookups).

Fails if a ZIP is unknown or its county is in another state, so a typo can't put a base in the wrong place.
Output: shared/data/bases.js (GOVPAY_DATA.bases)
Usage:  python3 scripts/build-bases.py
"""
import json, sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    zfile = sorted((ROOT / "data/bah").glob("zips-*.json"))[-1]
    zips = json.loads(zfile.read_text())["zips"]
    counties = {c[0]: c for c in json.loads((ROOT / "data/places/counties.json").read_text())["counties"]}
    by_pfx = {}
    for z, (mha, c) in zips.items():
        if c:
            by_pfx.setdefault(z[:3] + mha, Counter())[c] += 1
    src = json.loads((ROOT / "data/places/bases.json").read_text())["bases"]
    out, errors, names = [], [], set()
    for name, st, zip_, *aliases in src:
        if name.lower() in names:
            errors.append(f"{name}: listed twice")
        names.add(name.lower())
        if zip_ not in zips:
            errors.append(f"{name}: ZIP {zip_} isn't in {zfile.name}")
            continue
        mha, fips = zips[zip_]
        inferred = 0
        override = [a for a in aliases if a.startswith("county:")]
        aliases = [a for a in aliases if not a.startswith("county:")]
        if override:
            fips = override[0][7:]
        elif not fips:
            tally = by_pfx.get(zip_[:3] + mha)
            if not tally:
                errors.append(f"{name}: ZIP {zip_} has no county")
                continue
            fips, inferred = tally.most_common(1)[0][0], 1
        c = counties.get(fips)
        if not c or c[2] != st:
            errors.append(f"{name} ({st}): ZIP {zip_} is in {c[1] + ', ' + c[2] if c else fips}")
            continue
        out.append([name, zip_, mha, fips, inferred] + [a.lower() for a in aliases])
        print(f"{name:48} {st} {zip_} {mha}  {c[1]}{' (inferred)' if inferred else ''}")
    if errors:
        sys.exit("\n".join(errors))
    data = {"source": "data/places/bases.json (hand-kept); housing area and county from DTMO + Census ZIP data",
            "bases": out}
    (ROOT / "shared/data/bases.js").write_text(
        "/* Generated by scripts/build-bases.py from data/places/bases.json. Do not edit by hand. */\n"
        "(function (g) { (g.GOVPAY_DATA = g.GOVPAY_DATA || {}).bases = " + json.dumps(data, separators=(",", ":")) +
        "; })(typeof window !== 'undefined' ? window : globalThis);\n")
    print(f"{len(out)} installations -> shared/data/bases.js")


main()
