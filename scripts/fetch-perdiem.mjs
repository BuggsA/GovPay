#!/usr/bin/env node
/*
 * Download real CONUS per diem rates from the GSA Per Diem API and write:
 *   data/perdiem/FY<year>.json   – one normalized file per fiscal year (kept in git, easy to diff)
 *   shared/data/perdiem.js       – the same data bundled for the browser
 *
 * Usage:  GSA_API_KEY=xxxx node scripts/fetch-perdiem.mjs [FY ...]
 *   Default fiscal years: last, current and next (FY starts Oct 1).
 *   GSA_API_KEY: free key from https://api.data.gov/signup/ (DEMO_KEY works for a few calls).
 *
 * Source: https://open.gsa.gov/api/perdiem/
 */
import { mkdir, writeFile, readFile, readdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const KEY = process.env.GSA_API_KEY || "DEMO_KEY";
const API = "https://api.gsa.gov/travel/perdiem/v2/rates/conus";
const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

function currentFY(d = new Date()) { return d.getMonth() >= 9 ? d.getFullYear() + 1 : d.getFullYear(); }
const clean = (s) => (s == null ? null : String(s).replace(/\s+/g, " ").trim());
export const areaId = (state, city) => `${state}:${clean(city)}`;

async function get(path) {
  const url = `${API}/${path}?api_key=${KEY}`;
  const res = await fetch(url, { headers: { Accept: "application/json" } });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${API}/${path}`);
  return res.json();
}

async function fetchYear(fy) {
  const [lodging, mie] = await Promise.all([get(`lodging/${fy}`), get(`mie/${fy}`)]);
  const standard = {};
  const areas = [];
  for (const r of lodging) {
    const city = clean(r.City), state = clean(r.State);
    const row = { state, city, county: clean(r.County), mie: Number(r.Meals), lodging: MONTHS.map((m) => Number(r[m])) };
    if (city === "Standard Rate") standard[state] = { mie: row.mie, lodging: row.lodging };
    else areas.push(Object.assign({ id: areaId(state, city) }, row));
  }
  // De-duplicate areas that GSA lists under several states (e.g. the DC area under DC, MD and VA).
  const byId = {};
  for (const a of areas) byId[a.id] = a;
  const stdValues = Object.values(standard);
  return {
    fy,
    source: "GSA Per Diem API (open.gsa.gov/api/perdiem)",
    fetchedAt: new Date().toISOString().slice(0, 10),
    note: `FY${fy} runs Oct 1, ${fy - 1} to Sep 30, ${fy}. Lodging is listed Jan..Dec.`,
    standard: stdValues[0],          // the same CONUS standard rate in every state
    mieTiers: mie.map((t) => ({ total: t.total, breakfast: t.breakfast, lunch: t.lunch, dinner: t.dinner, incidental: t.incidental, firstLastDay: t.FirstLastDay })),
    areas: Object.values(byId).sort((a, b) => a.id.localeCompare(b.id)),
  };
}

async function main() {
  const years = process.argv.slice(2).map(Number).filter(Boolean);
  const fys = years.length ? years : [currentFY() - 1, currentFY(), currentFY() + 1];
  await mkdir(join(root, "data/perdiem"), { recursive: true });
  for (const fy of fys) {
    try {
      const data = await fetchYear(fy);
      await writeFile(join(root, `data/perdiem/FY${fy}.json`), JSON.stringify(data, null, 1) + "\n");
      console.log(`FY${fy}: ${data.areas.length} areas, standard $${data.standard.lodging[0]} + $${data.standard.mie}`);
    } catch (e) {
      console.warn(`FY${fy}: skipped (${e.message})`); // next FY may not be published yet
    }
  }
  // Bundle every FY file on disk for the browser.
  const files = (await readdir(join(root, "data/perdiem"))).filter((f) => /^FY\d{4}\.json$/.test(f)).sort();
  const bundle = {};
  for (const f of files) {
    const d = JSON.parse(await readFile(join(root, "data/perdiem", f), "utf8"));
    bundle[d.fy] = { fetchedAt: d.fetchedAt, standard: d.standard, mieTiers: d.mieTiers,
      areas: Object.fromEntries(d.areas.map((a) => [a.id, [a.city, a.county, a.mie, a.lodging]])) };
  }
  await mkdir(join(root, "shared/data"), { recursive: true });
  await writeFile(join(root, "shared/data/perdiem.js"),
    "/* Generated by scripts/fetch-perdiem.mjs from the GSA Per Diem API. Do not edit by hand. */\n" +
    "(function (g) { (g.GOVPAY_DATA = g.GOVPAY_DATA || {}).perDiem = " + JSON.stringify(bundle) + "; })(typeof window !== 'undefined' ? window : globalThis);\n");
  console.log(`bundled ${files.length} fiscal years -> shared/data/perdiem.js`);
}

main().catch((e) => { console.error(e); process.exit(1); });
