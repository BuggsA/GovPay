#!/usr/bin/env python3
"""
Convert the USAJOBS occupational series code list into shared/data/series.js (GOVPAY_DATA.series).

Input:  data/raw/usajobs/occupational-series.txt  (code|name|status, transcribed from the USAJOBS JSON)
Output: shared/data/series.js and data/series.json
        { names: {code: name}, retired: [codes], families: {"0300": "Administration..."}, leo: [codes] }

Series 0000-2299 are white-collar (General Schedule); 2500 and up are trades (Federal Wage System).
Run: python3 scripts/convert-series.py
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SMALL = {"and", "or", "of", "the", "for", "in", "to", "a", "an", "on", "by"}
# Law enforcement series that usually carry LEO special rates (5 U.S.C. 5541(3) positions):
# criminal investigators, Border Patrol agents, CBP officers, police, correctional officers, deputy U.S. marshals.
LEO = ["0007", "0082", "0083", "1811", "1895", "1896"]
# Job family names: the "General"/"Miscellaneous" x01 series of each family, simplified
FAMILY_NAMES = {
    "0000": "Miscellaneous occupations", "0100": "Social science, psychology and welfare", "0200": "Human resources",
    "0300": "Administration, clerical and office services", "0400": "Natural resources and biological sciences",
    "0500": "Accounting and budget", "0600": "Medical, hospital, dental and public health", "0700": "Veterinary medical science",
    "0800": "Engineering and architecture", "0900": "Legal and kindred", "1000": "Information and arts",
    "1100": "Business and industry", "1200": "Copyright, patent and trademark", "1300": "Physical sciences",
    "1400": "Library and archives", "1500": "Mathematical sciences", "1600": "Equipment, facilities and services",
    "1700": "Education", "1800": "Investigation and inspection", "1900": "Quality assurance and grading",
    "2000": "Supply", "2100": "Transportation", "2200": "Information technology", "2300": "Postal",
}


def tidy(name):
    name = re.sub(r"\s+Series$", "", name.strip())
    words = name.split()
    out = []
    for i, w in enumerate(words):
        lw = w.lower()
        out.append(lw if i > 0 and lw in SMALL else w)
    return " ".join(out)


def main():
    names, retired = {}, []
    for line in (ROOT / "data/raw/usajobs/occupational-series.txt").read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        code, name, status = line.split("|")
        assert re.fullmatch(r"\d{4}", code) and code not in names, code
        names[code] = tidy(name)
        if status == "retired":
            retired.append(code)
    for c in ["0343", "2210", "1811", "0801", "1102", "0560"]:
        assert c in names and c not in retired, c
    assert names["0343"] == "Management and Program Analysis", names["0343"]
    doc = {"source": "USAJOBS occupational series code list, generated 2026-10-31", "names": names, "retired": retired,
           "families": FAMILY_NAMES, "leo": LEO}
    (ROOT / "data/series.json").write_text(json.dumps(doc, indent=1) + "\n")
    (ROOT / "shared/data/series.js").write_text(
        "/* Generated by scripts/convert-series.py from the USAJOBS code list. Do not edit by hand. */\n"
        "(function (g) { (g.GOVPAY_DATA = g.GOVPAY_DATA || {}).series = " + json.dumps(doc, separators=(",", ":")) +
        "; })(typeof window !== \"undefined\" ? window : globalThis);\n")
    gs = [c for c in names if c < "2300" and c not in retired]
    print(f"{len(names)} series ({len(retired)} retired); {len(gs)} active white-collar (GS), "
          f"{len([c for c in names if c >= '2500' and c not in retired])} active trades (FWS)")


if __name__ == "__main__":
    main()
