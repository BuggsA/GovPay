#!/usr/bin/env python3
"""
Convert OPM's law enforcement officer (LEO) pay file into the engine's LEO base table.

Input:  data/raw/opm/<year>/<year>-law-enforcement-officer-pay-rates.xlsx  (OPM "ALLLEO": one table per
        locality area plus "GL", the LEO base table before locality; downloaded by hand, OPM blocks scripts)
        data/payorder/<year>.json  (GS base table, locality percentages and EX-IV cap from the pay order)
Output: shared/data/leo.js (GOVPAY_DATA.leo = {year: {grade: [10 steps]}}) and data/opm/<year>/leo.json

Checks: every one of the 58 locality tables must equal GL x (1 + locality %) rounded, capped at EX-IV, for
every grade and step; the area codes (DCB, SD, RUS...) are matched to areas by those numbers, not by name.
GL must equal the GS base table at GS-1, GS-2 and GS-11 to GS-15 (special LEO rates cover GS-3 to GS-10).

Usage: python3 scripts/convert-leo.py 2026   (needs openpyxl)
"""
import json, sys
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parent.parent


def with_locality(base, pct, cap):
    """OPM rounds to the nearest dollar, halves up (Python's round() would send $x.50 to even: Houston's 35% hits it)."""
    v = (Decimal(base) * (Decimal(100) + Decimal(str(pct))) / Decimal(100)).quantize(Decimal(1), rounding=ROUND_HALF_UP)
    return min(int(v), cap)


def main():
    year = int(sys.argv[1]) if len(sys.argv) > 1 else 2026
    src = ROOT / f"data/raw/opm/{year}/{year}-law-enforcement-officer-pay-rates.xlsx"
    ws = openpyxl.load_workbook(src, data_only=True, read_only=True)["ALLLEO"]
    rows = list(ws.iter_rows(values_only=True))
    hdr = rows[0]
    tables = {}
    for r in rows[1:]:
        if not r[0]:
            continue
        d = dict(zip(hdr, r))
        code = str(d["LOCNAME"]).replace("(LEO)", "").strip()
        tables.setdefault(code, {})[int(d["GRADE"])] = [int(d[f"ANNUAL{i}"]) for i in range(1, 11)]
    gl = tables.pop("GL")
    assert sorted(gl) == list(range(1, 16)), sorted(gl)

    order = json.loads((ROOT / f"data/payorder/{year}.json").read_text())
    gs = {int(g): v for g, v in order["gs"].items()}
    cap = order["executiveSchedule"]["IV"]
    for g in (1, 2, 11, 12, 13, 14, 15):
        assert gl[g] == gs[g], f"GL-{g} differs from the GS base table"
    for g in range(3, 11):
        assert all(a > b for a, b in zip(gl[g], gs[g])), f"GL-{g} should be above GS-{g}"

    matched, unmatched = {}, []
    for code, t in tables.items():
        hits = [a for a in order["locality"] if all(
            t[g][s] == with_locality(gl[g][s], a["pct"], cap) for g in range(1, 16) for s in range(10))]
        if len(hits) == 1:
            matched[code] = hits[0]["name"]
        else:
            unmatched.append(f"{code} ({len(hits)} matches)")
    if unmatched or len(matched) != len(order["locality"]):
        raise SystemExit(f"locality tables that don't follow GL x locality: {unmatched}; matched {len(matched)}")

    out = ROOT / f"data/opm/{year}"
    out.mkdir(parents=True, exist_ok=True)
    (out / "leo.json").write_text(json.dumps({"year": year, "source": src.name, "base": gl, "areaCodes": matched}, indent=1) + "\n")
    # shared file holds every converted year
    years = {}
    for p in sorted((ROOT / "data/opm").glob("*/leo.json")):
        d = json.loads(p.read_text())
        years[str(d["year"])] = {str(g): v for g, v in d["base"].items()}
    doc = {"source": "OPM law enforcement officer special base rates (ALLLEO file)", "years": years}
    (ROOT / "shared/data/leo.js").write_text(
        "/* Generated by scripts/convert-leo.py from OPM's LEO pay files. Do not edit by hand. */\n"
        "(function (g) { (g.GOVPAY_DATA = g.GOVPAY_DATA || {}).leo = " + json.dumps(doc, separators=(",", ":")) +
        "; })(typeof window !== \"undefined\" ? window : globalThis);\n")
    print(f"{year}: LEO base table OK; all {len(matched)} locality tables = GL x locality (capped at EX-IV ${cap:,})")


if __name__ == "__main__":
    main()
