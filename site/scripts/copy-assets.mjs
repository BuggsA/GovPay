// Copy the single-source engine, data, design files and calculator into public/
// so the built site serves exactly the code that the repo maintains once.
import { cp, mkdir, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const site = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(site, "..");
const pub = join(site, "public");
const copies = [
  ["shared/govpay.js", "shared/govpay.js"], ["shared/parse.js", "shared/parse.js"], ["shared/tax.js", "shared/tax.js"], ["shared/analytics.js", "shared/analytics.js"],
  ["shared/data", "shared/data"], ["sites/ledger/ui", "ui"], ["sites/ledger/app.js", "app.js"], ["sites/ledger/styles.css", "styles.css"],
];
await rm(join(pub, "shared"), { recursive: true, force: true });
await rm(join(pub, "ui"), { recursive: true, force: true });
for (const [from, to] of copies) {
  await mkdir(dirname(join(pub, to)), { recursive: true });
  await cp(join(repo, from), join(pub, to), { recursive: true });
}
console.log(`copied ${copies.length} sources into public/`);

// Self-hosted fonts (from @fontsource): no request to Google, and the page doesn't wait on another domain.
const FONTS = [["Familjen Grotesk", "familjen-grotesk", [600, 700]], ["Hanken Grotesk", "hanken-grotesk", [400, 500, 600, 700]], ["Spline Sans Mono", "spline-sans-mono", [500, 600]]];
await rm(join(pub, "fonts"), { recursive: true, force: true });
await mkdir(join(pub, "fonts"), { recursive: true });
let css = "/* Generated by scripts/copy-assets.mjs from @fontsource (latin subset). */\n";
for (const [family, pkg, weights] of FONTS) {
  for (const w of weights) {
    const file = `${pkg}-latin-${w}-normal.woff2`;
    await cp(join(site, "node_modules/@fontsource", pkg, "files", file), join(pub, "fonts", file));
    css += `@font-face{font-family:"${family}";font-style:normal;font-weight:${w};font-display:swap;src:url(/fonts/${file}) format("woff2")}\n`;
  }
}
await writeFile(join(pub, "fonts", "fonts.css"), css);
console.log(`copied ${FONTS.reduce((n, f) => n + f[2].length, 0)} font files into public/fonts/`);
